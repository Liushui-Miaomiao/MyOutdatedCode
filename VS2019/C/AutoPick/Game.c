/******************************************
 * @brief 检查游戏版本是否为汉化二代
 * 
 * @return 返回游戏版本是否为汉化二代
 ******************************************/
BOOL 
CheckVersion
(void) 
{
	// --------------------------------------------------------------------
	// 函数局部变量处理

	// 局部变量声明
	BOOL	bRet	;										/* 函数结果  */
	DWORD	dwVer	;										/* 游戏版本  */

	// 局部变量初始化
	bRet	= FALSE									;
	dwVer	= ReadMemory(g_hProcess, 0x42748E, 4, 0);

	// --------------------------------------------------------------------
	// 函数体

	// 如果游戏版本不匹配
	if (dwVer == 0xFF563DE8) {
		bRet = TRUE;
	}

	// --------------------------------------------------------------------
	// 函数返回前需要处理的过程
//CLOSE:

	// --------------------------------------------------------------------
	// 函数返回值
//RET:
	return bRet;
}

